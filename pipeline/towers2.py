def area(q): return sum(q[i][0]*q[(i+1)%len(q)][1]-q[(i+1)%len(q)][0]*q[i][1] for i in range(len(q)))/2
def build(ref_sign):
    T=[]
    for k,parts in P.items():
        ox,oy=ORG[k]; mx=max(l for l,_ in parts); seen=False
        for lv,pp in parts:
            q=[plan2s(ox+x/5,oy+y/5) for x,y in pp]
            if k=='1703': q=[((12.3 if 11<x<13 else x),-0.01) if abs(z)<1.6 and -4<x<29 else ((12.3,z) if 11.5<x<12.8 and z<9 else (x,z)) for x,z in q]
            if (area(q)>0)!=(ref_sign>0): q=q[::-1]
            top=(lv==mx and not seen); seen=seen or top
            T.append({'name':k,'levels':lv,'top':top,'p':[[round(x,2),round(z,2)] for x,z in q]})
    return T
